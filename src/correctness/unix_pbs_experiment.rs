fn evaluate_scheme(
    spec: &ParameterDescriptor,
    seed: u64,
    trials: usize,
    verbose: bool,
) -> SchemeResult {
    if verbose {
        eprintln!(
            "[unix_pbs_experiment] {}: generating client key",
            spec.label
        );
    }
    let params = complete_parameters(spec);
    let cks = ClientKey::new(params);
    if verbose {
        eprintln!(
            "[unix_pbs_experiment] {}: generating standard server key",
            spec.label
        );
    }
    let sks = ServerKey::new(&cks);
    if verbose {
        eprintln!(
            "[unix_pbs_experiment] {}: generating compressed server key",
            spec.label
        );
    }
    let compressed_sks = CompressedServerKey::new(&cks);
    if verbose {
        eprintln!(
            "[unix_pbs_experiment] {}: preparing key-decompression server key",
            spec.label
        );
    }
    let runtime_sks = prepare_decompressed_server_key(&compressed_sks);

    let message_modulus = cks.parameters().message_modulus().0;
    let lut = sks.generate_msg_lookup_table(|x| x * x, cks.parameters().message_modulus());

    let mut rng = StdRng::seed_from_u64(seed);

    if verbose {
        eprintln!(
            "[unix_pbs_experiment] {}: evaluating {} ciphertext trial(s)",
            spec.label, trials
        );
    }

    let mut message = 0;
    let mut expected = 0;
    let mut standard_decrypted = 0;
    let mut runtime_decompression_decrypted = 0;
    let mut successes = 0;
    let mut standard_successes = 0;
    let mut runtime_decompression_successes = 0;
    let mut path_match_successes = 0;

    for _ in 0..trials {
        let msg = rng.gen_range(0..message_modulus);
        let expected_value = (msg * msg) % message_modulus;
        let ct = cks.encrypt(msg);

        let standard_ct = sks.apply_lookup_table(&ct, &lut);
        let runtime_ct = apply_pbs_with_decompressed_key(&runtime_sks, &ct, &lut);

        let standard_dec = cks.decrypt(&standard_ct);
        let runtime_dec = cks.decrypt(&runtime_ct);
        let standard_trial_pass = standard_dec == expected_value;
        let runtime_trial_pass = runtime_dec == expected_value;
        let path_match = standard_dec == runtime_dec;
        let trial_pass = standard_trial_pass && runtime_trial_pass && path_match;

        if standard_trial_pass {
            standard_successes += 1;
        }
        if runtime_trial_pass {
            runtime_decompression_successes += 1;
        }
        if path_match {
            path_match_successes += 1;
        }
        if trial_pass {
            successes += 1;
        }

        message = msg;
        expected = expected_value;
        standard_decrypted = standard_dec;
        runtime_decompression_decrypted = runtime_dec;
    }

    let standard_pass = standard_successes == trials;
    let runtime_decompression_pass = runtime_decompression_successes == trials;
    let path_match = path_match_successes == trials;
    let pass = successes == trials;

    if verbose {
        eprintln!("[unix_pbs_experiment] {}: done, pass={}", spec.label, pass);
    }

    SchemeResult {
        label: spec.label.clone(),
        security_bits: spec.security_bits,
        polynomial_size: spec.polynomial_size,
        lwe_dimension: spec.lwe_dimension,
        glwe_dimension: spec.glwe_dimension,
        pbs_level: spec.pbs_level,
        message,
        expected,
        standard_decrypted,
        runtime_decompression_decrypted,
        standard_pass,
        runtime_decompression_pass,
        path_match,
        trials,
        successes,
        standard_successes,
        runtime_decompression_successes,
        path_match_successes,
        pass,
    }
}

fn prepare_decompressed_server_key(compressed_sks: &CompressedServerKey) -> ServerKey {
    compressed_sks.prepare_runtime_decompression_server_key()
}

fn apply_pbs_with_decompressed_key(
    decompressed_sks: &ServerKey,
    ct: &Ciphertext,
    lut: &LookupTableOwned,
) -> Ciphertext {
    decompressed_sks.apply_lookup_table(ct, lut)
}

fn complete_parameters(spec: &ParameterDescriptor) -> ClassicPBSParameters {
    let template = match spec.security_bits {
        0..=80 => V1_6_PARAM_MESSAGE_2_CARRY_2_KS_PBS_GAUSSIAN_2M40,
        81..=110 => V1_6_PARAM_MESSAGE_2_CARRY_2_KS_PBS_GAUSSIAN_2M64,
        _ => V1_6_PARAM_MESSAGE_2_CARRY_2_KS_PBS_GAUSSIAN_2M128,
    };

    let template_pbs_budget = template.pbs_base_log.0 * template.pbs_level.0;
    let derived_pbs_base_log =
        ((template_pbs_budget as u64 + spec.pbs_level - 1) / spec.pbs_level).max(1);

    let mut params = template;
    params.lwe_dimension = LweDimension(spec.lwe_dimension as usize);
    params.glwe_dimension = GlweDimension(spec.glwe_dimension as usize);
    params.polynomial_size = PolynomialSize(spec.polynomial_size as usize);
    params.pbs_level = DecompositionLevelCount(spec.pbs_level as usize);
    params.pbs_base_log =
        DecompositionBaseLog(spec.pbs_base_log.unwrap_or(derived_pbs_base_log) as usize);

    if let Some(ks_base_log) = spec.ks_base_log {
        params.ks_base_log = DecompositionBaseLog(ks_base_log as usize);
    }

    if let Some(ks_level) = spec.ks_level {
        params.ks_level = DecompositionLevelCount(ks_level as usize);
    }

    if let Some(lwe_log2_stddev) = spec.lwe_log2_stddev {
        params.lwe_noise_distribution = DynamicDistribution::new_gaussian_from_std_dev(
            StandardDev(2_f64.powf(lwe_log2_stddev)),
        );
    }

    if let Some(glwe_log2_stddev) = spec.glwe_log2_stddev {
        params.glwe_noise_distribution = DynamicDistribution::new_gaussian_from_std_dev(
            StandardDev(2_f64.powf(glwe_log2_stddev)),
        );
    }

    if let Some(log2_p_fail) = spec.log2_p_fail {
        params.log2_p_fail = log2_p_fail;
    }

    params
}

fn bool_word(value: bool) -> &'static str {
    if value {
        "True"
    } else {
        "False"
    }
}

fn format_accuracy(successes: usize, trials: usize) -> String {
    let percent = successes as f64 * 100.0 / trials as f64;
    format!("{successes}/{trials} ({percent:.2}%)")
}

fn format_scheme_summary(result: &SchemeResult, summary_tag: Option<&str>) -> String {
    let correctness_name = summary_tag.map_or_else(
        || String::from("correctness"),
        |tag| format!("correctness[{tag}]"),
    );
    let accuracy = if result.trials > 1 {
        format!(
            ", accuracy={}",
            format_accuracy(result.successes, result.trials)
        )
    } else {
        String::new()
    };

    format!(
        "{:<8} {} pass={}, standard={}{}",
        result.label,
        correctness_name,
        bool_word(result.pass),
        bool_word(result.standard_pass),
        accuracy
    )
}

fn format_summary(report: &ExperimentReport, summary_tag: Option<&str>) -> String {
    let mut lines = Vec::with_capacity(report.comparisons.len() * 2);
    for comparison in &report.comparisons {
        if let Some(baseline) = &comparison.baseline {
            lines.push(format_scheme_summary(baseline, summary_tag));
        }
        if let Some(optimized) = &comparison.optimized {
            lines.push(format_scheme_summary(optimized, summary_tag));
        }
    }
    lines.join("\n")
}
