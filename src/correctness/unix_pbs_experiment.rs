#[derive(Parser, Debug)]
#[command(version, about = "Correctness validation for SetA/UniX")]
struct Args {
    /// Built-in suite name. Ignored when --spec-file is provided.
    #[arg(long, default_value = "seta-unix")]
    suite: String,
    /// JSON suite generated by the security script.
    #[arg(long)]
    spec_file: Option<PathBuf>,
    /// Seed used for message generation.
    #[arg(long, default_value_t = 0)]
    seed: u64,
    /// Only run one comparison entry by index.
    #[arg(long)]
    entry_index: Option<usize>,
    /// Number of PBS trials per selected parameter. Defaults to one quick check.
    #[arg(long, default_value_t = 1)]
    trials: usize,
    /// Select which side of each comparison to run: all, seta, or unix.
    #[arg(long, default_value = "all", value_parser = ["all", "seta", "unix"])]
    scheme: String,
    /// Optional tag printed in the short summary. This only changes the name.
    #[arg(long)]
    summary_tag: Option<String>,
    /// Print full JSON details instead of the short command-line summary.
    #[arg(long)]
    json: bool,
    /// Print progress messages while generating keys and validating ciphertexts.
    #[arg(long)]
    verbose: bool,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
struct ParameterDescriptor {
    label: String,
    security_bits: u16,
    polynomial_size: u64,
    lwe_dimension: u64,
    glwe_dimension: u64,
    pbs_level: u64,
    #[serde(default)]
    pbs_base_log: Option<u64>,
    #[serde(default)]
    ks_base_log: Option<u64>,
    #[serde(default)]
    ks_level: Option<u64>,
    #[serde(default)]
    lwe_log2_stddev: Option<f64>,
    #[serde(default)]
    glwe_log2_stddev: Option<f64>,
    #[serde(default)]
    log2_p_fail: Option<f64>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
struct ComparisonEntry {
    baseline: ParameterDescriptor,
    optimized: ParameterDescriptor,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
struct ComparisonSuite {
    name: String,
    entries: Vec<ComparisonEntry>,
}

#[derive(Debug, Serialize)]
struct SchemeResult {
    label: String,
    security_bits: u16,
    polynomial_size: u64,
    lwe_dimension: u64,
    glwe_dimension: u64,
    pbs_level: u64,
    message: u64,
    expected: u64,
    standard_decrypted: u64,
    runtime_decompression_decrypted: u64,
    standard_pass: bool,
    runtime_decompression_pass: bool,
    path_match: bool,
    trials: usize,
    successes: usize,
    standard_successes: usize,
    runtime_decompression_successes: usize,
    path_match_successes: usize,
    pass: bool,
}

#[derive(Debug, Serialize)]
struct ComparisonResult {
    #[serde(skip_serializing_if = "Option::is_none")]
    baseline: Option<SchemeResult>,
    #[serde(skip_serializing_if = "Option::is_none")]
    optimized: Option<SchemeResult>,
}

#[derive(Debug, Serialize)]
struct ExperimentReport {
    suite: String,
    operation: &'static str,
    comparisons: Vec<ComparisonResult>,
}

fn main() {
    let args = Args::parse();
    if args.trials == 0 {
        panic!("--trials must be at least 1");
    }

    let mut suite = load_suite(&args);

    if let Some(entry_index) = args.entry_index {
        let total_entries = suite.entries.len();
        let entry = suite
            .entries
            .get(entry_index)
            .unwrap_or_else(|| panic!("entry index {entry_index} out of range 0..{total_entries}"))
            .clone();
        suite.entries = vec![entry];
    }

    if args.verbose {
        eprintln!(
            "[unix_pbs_experiment] suite={} entries={}",
            suite.name,
            suite.entries.len()
        );
    }

    let mut comparisons = Vec::with_capacity(suite.entries.len());
    let run_baseline = args.scheme == "all" || args.scheme == "seta";
    let run_optimized = args.scheme == "all" || args.scheme == "unix";

    for (index, entry) in suite.entries.iter().enumerate() {
        let human_index = index + 1;
        let total = suite.entries.len();
        let baseline = if run_baseline {
            if args.verbose {
                eprintln!(
                    "[unix_pbs_experiment] [{human_index}/{total}] baseline={}",
                    entry.baseline.label
                );
            }
            Some(evaluate_scheme(
                &entry.baseline,
                args.seed.wrapping_add(index as u64 * 2),
                args.trials,
                args.verbose,
            ))
        } else {
            None
        };

        let optimized = if run_optimized {
            if args.verbose {
                eprintln!(
                    "[unix_pbs_experiment] [{human_index}/{total}] optimized={}",
                    entry.optimized.label
                );
            }
            Some(evaluate_scheme(
                &entry.optimized,
                args.seed.wrapping_add(index as u64 * 2 + 1),
                args.trials,
                args.verbose,
            ))
        } else {
            None
        };

        if !run_baseline && !run_optimized {
            eprintln!("[unix_pbs_experiment] [{human_index}/{total}] no scheme selected");
        }

        comparisons.push(ComparisonResult {
            baseline,
            optimized,
        });
    }

    let report = ExperimentReport {
        suite: suite.name,
        operation: "single_square_pbs_correctness",
        comparisons,
    };

    if args.json {
        let report_json = serde_json::to_string_pretty(&report).unwrap();
        println!("{report_json}");
    } else {
        println!("{}", format_summary(&report, args.summary_tag.as_deref()));
    }

    if !report.comparisons.iter().all(|comparison| {
        comparison
            .baseline
            .as_ref()
            .map_or(true, |result| result.pass)
            && comparison
                .optimized
                .as_ref()
                .map_or(true, |result| result.pass)
    }) {
        std::process::exit(1);
    }
}

fn load_suite(args: &Args) -> ComparisonSuite {
    if let Some(path) = &args.spec_file {
        let data = fs::read_to_string(path)
            .unwrap_or_else(|err| panic!("failed to read suite file {}: {err}", path.display()));
        serde_json::from_str(&data)
            .unwrap_or_else(|err| panic!("failed to parse suite file {}: {err}", path.display()))
    } else {
        match args.suite.as_str() {
            "seta-unix" => built_in_seta_unix_suite(),
            other => panic!("unknown built-in suite '{other}', use --spec-file for custom suites"),
        }
    }
}

