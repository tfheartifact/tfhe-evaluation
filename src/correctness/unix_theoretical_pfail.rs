fn evaluate_scheme(spec: &ParameterDescriptor) -> SchemeTheoryResult {
    let params = complete_parameters(spec);
    let theoretical = theoretical_failure_for_classic_pbs(&params);
    let precision_bits = precision_bits_override(spec);
    let configured_log2_p_fail = if precision_bits.is_some() && spec.log2_p_fail.is_none() {
        None
    } else {
        Some(spec.log2_p_fail.unwrap_or(params.log2_p_fail))
    };

    SchemeTheoryResult {
        label: spec.label.clone(),
        precision_bits,
        security_bits: spec.security_bits,
        polynomial_size: spec.polynomial_size,
        lwe_dimension: spec.lwe_dimension,
        glwe_dimension: spec.glwe_dimension,
        pbs_level: spec.pbs_level,
        configured_log2_p_fail,
        theoretical,
    }
}

fn theoretical_failure_for_classic_pbs(params: &ClassicPBSParameters) -> TheoreticalFailureStats {
    let modulus = NoiseSimulationModulus::from_ciphertext_modulus(params.ciphertext_modulus);
    let accumulator = NoiseSimulationGlwe::new(
        params.glwe_dimension,
        params.polynomial_size,
        Variance(0.0),
        modulus,
    );
    let small_lwe_dimension = params.lwe_dimension;
    let big_lwe_dimension = params
        .glwe_dimension
        .to_equivalent_lwe_dimension(params.polynomial_size);

    let bsk = NoiseSimulationLweFourierBsk::new(
        small_lwe_dimension,
        params.glwe_dimension.to_glwe_size(),
        params.polynomial_size,
        params.pbs_base_log,
        params.pbs_level,
        params.glwe_noise_distribution,
        modulus,
    );

    let pbs_input = NoiseSimulationLwe::new(small_lwe_dimension, Variance(0.0), modulus);
    let mut after_pbs = accumulator.allocate_lwe_bootstrap_result(&mut ());
    bsk.lwe_classic_fft_pbs(&pbs_input, &mut after_pbs, &accumulator, &mut ());

    let final_variance = match params.encryption_key_choice {
        EncryptionKeyChoice::Big => after_pbs.variance(),
        EncryptionKeyChoice::Small => {
            let ksk = NoiseSimulationLweKeyswitchKey::new(
                big_lwe_dimension,
                small_lwe_dimension,
                params.ks_base_log,
                params.ks_level,
                params.lwe_noise_distribution,
                modulus,
            );
            let mut after_ks = ksk.allocate_lwe_keyswitch_result(&mut ());
            ksk.lwe_keyswitch(&after_pbs, &mut after_ks, &mut ());
            after_ks.variance()
        }
    };

    let pfail = expected_pfail_for_precision(
        precision_with_padding(params.message_modulus, params.carry_modulus),
        final_variance,
    );
    let log2_p_fail = log2_pfail_for_precision(
        precision_with_padding(params.message_modulus, params.carry_modulus),
        final_variance,
    );

    TheoreticalFailureStats {
        variance: final_variance.0,
        p_fail: pfail,
        log2_p_fail,
    }
}

fn precision_with_padding(msg_mod: MessageModulus, carry_mod: CarryModulus) -> u32 {
    let cleartext_modulus = msg_mod.0 * carry_mod.0;
    assert!(cleartext_modulus.is_power_of_two());
    cleartext_modulus.ilog2() + 1
}

fn expected_pfail_for_precision(precision_with_padding: u32, variance: Variance) -> f64 {
    let precision_for_proper_decryption: i32 = (precision_with_padding + 1).try_into().unwrap();
    let correctness_threshold = 2.0f64.powi(-precision_for_proper_decryption);
    let measured_std_dev = variance.0.sqrt();
    let measured_std_score = correctness_threshold / measured_std_dev;
    statrs::function::erf::erfc(measured_std_score / core::f64::consts::SQRT_2)
}

fn log2_pfail_for_precision(precision_with_padding: u32, variance: Variance) -> f64 {
    let precision_for_proper_decryption: i32 = (precision_with_padding + 1).try_into().unwrap();
    let correctness_threshold = 2.0f64.powi(-precision_for_proper_decryption);
    let measured_std_dev = variance.0.sqrt();
    let measured_std_score = correctness_threshold / measured_std_dev;
    let scaled_score = measured_std_score / core::f64::consts::SQRT_2;
    let pfail = statrs::function::erf::erfc(scaled_score);

    if pfail > 0.0 {
        pfail.log2()
    } else {
        (-scaled_score * scaled_score - scaled_score.ln() - 0.5 * core::f64::consts::PI.ln())
            / core::f64::consts::LN_2
    }
}

fn complete_parameters(spec: &ParameterDescriptor) -> ClassicPBSParameters {
    let template = match spec.security_bits {
        0..=80 => V1_6_PARAM_MESSAGE_2_CARRY_2_KS_PBS_GAUSSIAN_2M40,
        81..=110 => V1_6_PARAM_MESSAGE_2_CARRY_2_KS_PBS_GAUSSIAN_2M64,
        _ => V1_6_PARAM_MESSAGE_2_CARRY_2_KS_PBS_GAUSSIAN_2M128,
    };

    let template_pbs_budget = template.pbs_base_log.0 * template.pbs_level.0;
    let derived_pbs_base_log =
        ((template_pbs_budget as u64 + spec.pbs_level - 1) / spec.pbs_level).max(1);

    let mut params = template;
    params.lwe_dimension = LweDimension(spec.lwe_dimension as usize);
    params.glwe_dimension = GlweDimension(spec.glwe_dimension as usize);
    params.polynomial_size = PolynomialSize(spec.polynomial_size as usize);
    params.pbs_level = DecompositionLevelCount(spec.pbs_level as usize);
    params.pbs_base_log =
        DecompositionBaseLog(spec.pbs_base_log.unwrap_or(derived_pbs_base_log) as usize);

    if let Some(ks_base_log) = spec.ks_base_log {
        params.ks_base_log = DecompositionBaseLog(ks_base_log as usize);
    }

    if let Some(ks_level) = spec.ks_level {
        params.ks_level = DecompositionLevelCount(ks_level as usize);
    }

    if spec.ks_base_log.is_some() || spec.ks_level.is_some() {
        params.encryption_key_choice = EncryptionKeyChoice::Small;
    }

    if let Some(lwe_log2_stddev) = spec.lwe_log2_stddev {
        params.lwe_noise_distribution = DynamicDistribution::new_gaussian_from_std_dev(
            StandardDev(2_f64.powf(lwe_log2_stddev)),
        );
    }

    if let Some(glwe_log2_stddev) = spec.glwe_log2_stddev {
        params.glwe_noise_distribution = DynamicDistribution::new_gaussian_from_std_dev(
            StandardDev(2_f64.powf(glwe_log2_stddev)),
        );
    }

    if let Some(log2_p_fail) = spec.log2_p_fail {
        params.log2_p_fail = log2_p_fail;
    }

    if let Some(precision_bits) = precision_bits_override(spec) {
        params.message_modulus = MessageModulus(1u64 << precision_bits);
        params.carry_modulus = CarryModulus(1);
    }

    params
}

fn precision_bits_override(spec: &ParameterDescriptor) -> Option<u32> {
    spec.label
        .rsplit_once("-p")
        .and_then(|(_, suffix)| suffix.parse::<u32>().ok())
}
